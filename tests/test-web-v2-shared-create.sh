#!/usr/bin/env bash
set -Eeuo pipefail
ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
export RUNNER_TOOLS_LIB_ONLY=1
source "$ROOT/scripts/register-runner.sh"
TRACE=""
web_create_stage() { TRACE="${TRACE}WEB:$1;"; }
cli_create_authority() { TRACE="${TRACE}CLI:$1:$2:$3;"; }
WEB_MODE=1
for stage in PRE_REGISTRATION REGISTERED_PERMISSION_INCOMPLETE REGISTERED_UNIT_INCOMPLETE REGISTERED_START_INCOMPLETE REGISTERED_HEALTH_UNKNOWN CREATE_COMPLETE; do create_lifecycle_stage "$stage"; done
EXPECTED_WEB="WEB:PRE_REGISTRATION;WEB:REGISTERED_PERMISSION_INCOMPLETE;WEB:REGISTERED_UNIT_INCOMPLETE;WEB:REGISTERED_START_INCOMPLETE;WEB:REGISTERED_HEALTH_UNKNOWN;WEB:CREATE_COMPLETE;"
[[ "$TRACE" == "$EXPECTED_WEB" ]] || { echo "Unexpected Executor stages" >&2; exit 1; }
TRACE=""
WEB_MODE=0
for stage in PRE_REGISTRATION REGISTERED_PERMISSION_INCOMPLETE REGISTERED_UNIT_INCOMPLETE REGISTERED_START_INCOMPLETE REGISTERED_HEALTH_UNKNOWN CREATE_COMPLETE; do create_lifecycle_stage "$stage"; done
EXPECTED_CLI="CLI:stage:PRE_REGISTRATION:-;CLI:stage:REGISTERED_PERMISSION_INCOMPLETE:-;CLI:stage:REGISTERED_UNIT_INCOMPLETE:-;CLI:stage:REGISTERED_START_INCOMPLETE:-;CLI:stage:REGISTERED_HEALTH_UNKNOWN:-;CLI:stage:CREATE_COMPLETE:-;"
[[ "$TRACE" == "$EXPECTED_CLI" ]] || { echo "Unexpected terminal stages" >&2; exit 1; }
echo "PASS: terminal and executor share the actual Create checkpoint function"
